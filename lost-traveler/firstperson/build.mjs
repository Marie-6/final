// Joins src/*.js (in file-name order) into game.js, which index.html loads.
//   node lost-traveler/firstperson/build.mjs           build once
//   node lost-traveler/firstperson/build.mjs --watch   rebuild whenever a file in src/ changes
//   node lost-traveler/firstperson/build.mjs --where 1234   which src file is game.js line 1234?
// Never edit game.js by hand: it is overwritten on every build.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = path.dirname(fileURLToPath(import.meta.url));
const srcDir = path.join(dir, 'src');
const outPath = path.join(dir, 'game.js');
const HEADER = '// GENERATED by build.mjs from src/ - do not edit this file, edit src/ and rebuild.';

const files = () => fs.readdirSync(srcDir).filter(f => f.endsWith('.js')).sort();

export function build(quiet = false) {
  const out = [HEADER];
  for (const f of files()) {
    const text = fs.readFileSync(path.join(srcDir, f), 'utf8').replace(/\n$/, '');
    out.push(`//@src ${f}`, text);
  }
  fs.writeFileSync(outPath, out.join('\n') + '\n');
  if (!quiet) console.log(`built game.js from ${files().length} files (${new Date().toLocaleTimeString()})`);
}

function where(n) {
  const lines = fs.readFileSync(outPath, 'utf8').split('\n');
  let file = null, start = 0;
  for (let i = 0; i < n && i < lines.length; i++) {
    const m = lines[i].match(/^\/\/@src (.+)$/);
    if (m) { file = m[1]; start = i + 1; }
  }
  console.log(file ? `game.js:${n}  ->  src/${file}:${n - start}` : 'line is outside any src file');
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const args = process.argv.slice(2);
  if (args[0] === '--where') where(Number(args[1]));
  else {
    build(args.includes('--quiet'));
    if (args.includes('--watch')) {
      let t;
      fs.watch(srcDir, () => { clearTimeout(t); t = setTimeout(() => build(), 80); });
      console.log('watching src/ ... (Ctrl+C to stop)');
    }
  }
}
